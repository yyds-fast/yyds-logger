def get_message(language: str, key: str, **kwargs) -> str:
    """Return a localized message, falling back to Chinese for bad locales."""
    messages = LANG_MAP.get(str(language).strip().lower()) or LANG_MAP["zh"]
    text = messages.get(key, key)
    if not kwargs:
        return text
    try:
        return text.format(**{name: str(value) for name, value in kwargs.items()})
    except Exception:
        return text
